/**
 * Shared seeding context. Every write in the demo seeder goes through
 * `ensure`, which makes the whole run idempotent and non-destructive:
 *
 *   - look the record up by its natural key;
 *   - if it exists, reuse its _id and leave it exactly as it is (no updates);
 *   - otherwise create it through the Mongoose model, so schema validation,
 *     defaults and indexes apply just as they do for the API.
 *
 * In dry-run mode nothing is written: a missing record is counted as
 * "planned" and a placeholder ObjectId is returned so dependent records can
 * still be planned (their lookups by that id simply find nothing).
 */
import { Types, type Model } from 'mongoose';
import PDFDocument from 'pdfkit';

export interface Tally {
  existing: number;
  created: number;
  planned: number;
}

export class SeedContext {
  readonly tallies = new Map<string, Tally>();
  readonly now = new Date();

  constructor(readonly apply: boolean) {}

  private tally(label: string): Tally {
    let t = this.tallies.get(label);
    if (!t) {
      t = { existing: 0, created: 0, planned: 0 };
      this.tallies.set(label, t);
    }
    return t;
  }

  daysFromNow(days: number, hour = 10): Date {
    const d = new Date(this.now.getTime() + days * 86_400_000);
    d.setUTCHours(hour - 6, 30, 0, 0); // `hour` is IST wall-clock (UTC+05:30)
    return d;
  }

  /**
   * Find-or-create. `build` is only called when the record is missing, and
   * `backdate` (if given) sets createdAt/updatedAt on a record this run just
   * created — a raw update, because Mongoose timestamps would overwrite them.
   */
  async ensure<T>(
    label: string,
    model: Model<T>,
    filter: Record<string, unknown>,
    build: () => Record<string, unknown> | Promise<Record<string, unknown>>,
    backdate?: Date,
  ): Promise<Types.ObjectId> {
    const existing = await model.findOne(filter).select('_id').lean<{ _id: Types.ObjectId }>();
    if (existing) {
      this.tally(label).existing++;
      return existing._id;
    }
    if (!this.apply) {
      this.tally(label).planned++;
      return new Types.ObjectId();
    }
    const doc = await model.create(await build());
    const id = (doc as unknown as { _id: Types.ObjectId })._id;
    if (backdate) {
      await model.collection.updateOne(
        { _id: id },
        { $set: { createdAt: backdate, updatedAt: backdate } },
      );
    }
    this.tally(label).created++;
    return id;
  }

  /** Read-only lookup of an existing id (used to resolve references). */
  async findId<T>(model: Model<T>, filter: Record<string, unknown>) {
    const doc = await model.findOne(filter).select('_id').lean<{ _id: Types.ObjectId }>();
    return doc?._id;
  }
}

/** Small, valid PDF so resume/certificate downloads work like real uploads. */
export function renderPdf(title: string, lines: string[]): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const pdf = new PDFDocument({ size: 'A4', margin: 56 });
    const chunks: Buffer[] = [];
    pdf.on('data', (c: Buffer) => chunks.push(c));
    pdf.on('end', () => resolve(Buffer.concat(chunks)));
    pdf.on('error', reject);
    pdf.fontSize(20).text(title);
    pdf.moveDown();
    pdf.fontSize(10).fillColor('#666').text('Demo document generated by the AcadIn demo seeder.');
    pdf.moveDown().fillColor('#000').fontSize(11);
    for (const line of lines) pdf.text(line).moveDown(0.3);
    pdf.end();
  });
}

